/**
 * Generates lib/foreign-resources.yaml (Special:Version credits and SBOM) from
 * lib/ve/lib/foreign-resources.yaml.
 *
 * A library is credited if the extension ships any of its files: by path in extension.json
 * or includes/, or via a veModules entry. Others (e.g. jquery, OOUI) are provided by MediaWiki.
 *
 * Usage: node build/updateForeignResources.js [--check]
 *
 * Then regenerate lib/foreign-resources.cdx.json from MediaWiki core:
 *   php maintenance/run.php manageForeignResources make-cdx --extension=VisualEditor
 */

'use strict';

const fs = require( 'fs' );
const path = require( 'path' );
const yaml = require( 'js-yaml' );

const ROOT = path.resolve( __dirname, '..' );
const OUTPUT = path.join( ROOT, 'lib/foreign-resources.yaml' );

const registry = yaml.load( fs.readFileSync( path.join( ROOT, 'lib/ve/lib/foreign-resources.yaml' ), 'utf8' ) );
const extensionJson = require( '../extension.json' );
const modulesJson = require( '../lib/ve/build/modules.json' );

function getShippedLibs() {
	const libs = new Set();
	const addFromString = ( str, prefix ) => {
		for ( const match of str.matchAll( new RegExp( prefix + '([^/"\']+)/', 'g' ) ) ) {
			libs.add( match[ 1 ] );
		}
	};

	addFromString( JSON.stringify( extensionJson ), 'lib/ve/lib/' );
	const phpFiles = fs.readdirSync( path.join( ROOT, 'includes' ), { recursive: true } )
		.filter( ( file ) => file.endsWith( '.php' ) );
	for ( const file of phpFiles ) {
		addFromString( fs.readFileSync( path.join( ROOT, 'includes', file ), 'utf8' ), 'lib/ve/lib/' );
	}

	for ( const module of Object.values( extensionJson.ResourceModules ) ) {
		for ( const veModule of module.veModules || [] ) {
			addFromString( JSON.stringify( modulesJson[ veModule ] || {} ), '"lib/' );
		}
	}
	return libs;
}

function generate() {
	const shipped = getShippedLibs();
	for ( const lib of shipped ) {
		if ( !registry[ lib ] && lib !== 'codex-design-tokens' ) {
			throw new Error( `lib/ve/lib/${ lib } is shipped but missing from lib/ve/lib/foreign-resources.yaml` );
		}
	}

	const entries = {};
	const skipped = [];
	for ( const [ key, info ] of Object.entries( registry ) ) {
		if ( !shipped.has( key ) ) {
			skipped.push( key );
			continue;
		}
		entries[ info.name || key ] = {
			license: info.license,
			homepage: info.homepage,
			authors: info.authors,
			version: info.version || '—',
			type: 'doc-only'
		};
	}
	entries.VisualEditor = {
		license: 'MIT',
		homepage: 'https://www.mediawiki.org/wiki/VisualEditor',
		authors: 'VisualEditor Team and other contributors',
		version: 'Development branch',
		type: 'doc-only'
	};

	return '# Generated by build/updateForeignResources.js from lib/ve/lib/foreign-resources.yaml. Do not edit.\n' +
		'#\n' +
		'# Not listed, as they\'re provided by MediaWiki or not used by the extension:\n' +
		skipped.map( ( key ) => `# - ${ key }\n` ).join( '' ) +
		'\n' +
		Object.entries( entries )
			.map( ( [ name, info ] ) => yaml.dump( { [ name ]: info }, { lineWidth: -1 } ) )
			.join( '\n' );
}

const output = generate();
if ( process.argv.includes( '--check' ) ) {
	if ( fs.readFileSync( OUTPUT, 'utf8' ) !== output ) {
		console.error( 'lib/foreign-resources.yaml is out of date. Run `node build/updateForeignResources.js`.' );
		process.exitCode = 1;
	}
} else {
	fs.writeFileSync( OUTPUT, output );
}
